export function generateBigText(text: string, font: BigTextFont): string {
  if (!text) return '';

  const uppercaseText = text.toUpperCase();
  const fontDict = font === 'slant' ? SLANT_FONT : BLOCK_FONT;
  
  // Height is 5 lines for both fonts
  const lines: string[] = ['', '', '', '', ''];

  for (let i = 0; i < uppercaseText.length; i++) {
    const char = uppercaseText[i];
    const charLines = fontDict[char] || fontDict['?'];
    
    for (let r = 0; r < 5; r++) {
      // Add character segment, followed by a spacing column
      lines[r] += charLines[r] + '  ';
    }
  }

  return lines.join('\n');
}
